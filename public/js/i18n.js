function getLang() {
  const saved = typeof Store !== 'undefined' && Store.state ? Store.state.lang : null;
  return saved === 'pt' ? 'pt' : 'en';
}

function appLocale(lang) {
  return (lang || getLang()) === 'en' ? 'en-US' : 'pt-BR';
}

function t(key, vars, fallback) {
  const lang = getLang();
  const dict = I18N_DICT[lang] || I18N_DICT.pt;
  let str = dict[key];
  if (str === undefined) str = I18N_DICT.pt[key];
  if (str === undefined) str = fallback !== undefined ? fallback : key;
  if (vars && typeof str === 'string') {
    str = str.replace(/\{(\w+)\}/g, (_, k) => (vars[k] != null ? String(vars[k]) : ''));
  }
  return str;
}

const I18n = {
  applyStaticDOM() {
    const lang = getLang();
    if (typeof document === 'undefined' || !document.documentElement) return;
    document.documentElement.lang = lang === 'en' ? 'en' : 'pt-BR';

    const nodes = document.querySelectorAll ? document.querySelectorAll('[data-i18n]') : [];
    nodes.forEach(n => {
      const key = n.getAttribute('data-i18n');
      if (key) n.textContent = t(key);
    });

    const htmlNodes = document.querySelectorAll ? document.querySelectorAll('[data-i18n-html]') : [];
    htmlNodes.forEach(n => {
      const key = n.getAttribute('data-i18n-html');
      if (key) n.innerHTML = t(key);
    });

    const phNodes = document.querySelectorAll ? document.querySelectorAll('[data-i18n-placeholder]') : [];
    phNodes.forEach(n => {
      const key = n.getAttribute('data-i18n-placeholder');
      if (key) n.placeholder = t(key);
    });

    const titleNodes = document.querySelectorAll ? document.querySelectorAll('[data-i18n-title]') : [];
    titleNodes.forEach(n => {
      const key = n.getAttribute('data-i18n-title');
      if (key) n.title = t(key);
    });

    const ariaNodes = document.querySelectorAll ? document.querySelectorAll('[data-i18n-aria]') : [];
    ariaNodes.forEach(n => {
      const key = n.getAttribute('data-i18n-aria');
      if (key) n.setAttribute('aria-label', t(key));
    });
  },

  setLang(nextLang) {
    const lang = nextLang === 'en' ? 'en' : 'pt';
    if (typeof Store !== 'undefined' && Store.state) {
      Store.state.lang = lang;
      Store.save();
    }
    this.applyStaticDOM();

    if (typeof Router !== 'undefined' && typeof Router.syncLanguage === 'function') Router.syncLanguage();
    if (typeof QuotesUI !== 'undefined' && typeof QuotesUI.onLanguageChange === 'function') {
      QuotesUI.onLanguageChange();
    }
    if (typeof HomePage !== 'undefined') {
      HomePage.clockTick();
      HomePage.renderChips();
    }
    if (typeof TimerPage !== 'undefined') {
      if (typeof TimerPage.refreshHaloLabels === 'function') TimerPage.refreshHaloLabels();
      TimerPage.syncUI();
    }
    if (typeof TrackerPage !== 'undefined') {
      TrackerPage.renderControls();
      TrackerPage.render();
    }
    if (typeof TasksPage !== 'undefined') {
      TasksPage.syncComposeDueUI();
      TasksPage.render();
    }
    if (typeof Workspace !== 'undefined' && (Workspace.inited || Workspace.initialized) && typeof Workspace.syncLanguage === 'function') {
      Workspace.syncLanguage();
    }
    if (typeof LayoutEdit !== 'undefined' && LayoutEdit.active) {
      LayoutEdit.buildBar();
      LayoutEdit.decorate();
    }
    if (typeof Panel !== 'undefined') Panel.render();
  }
};

function setLang(lang) {
  I18n.setLang(lang);
}
